function build(
  raw: Array<[string, string]>,
  category: TabuCategory,
  difficulty: TabuDifficulty,
): TabuCard[] {
  return raw.map(([term, taboo]) => ({
    id: `${category}-${difficulty}-${term}`,
    term,
    taboo: taboo.split(',') as TabuCard['taboo'],
    category,
    difficulty,
  }));
}

